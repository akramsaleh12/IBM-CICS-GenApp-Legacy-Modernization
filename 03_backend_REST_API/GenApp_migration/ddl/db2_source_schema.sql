CREATE TABLE customer (
     customerNumber INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                     (START WITH 1000001, INCREMENT BY 1, CACHE 20),
     firstName      CHAR(10),
     lastName       CHAR(20),
     dateOfBirth    DATE,
     houseName      CHAR(20),
     houseNumber    CHAR(4),
     postcode       CHAR(8),
     phonehome      CHAR(20),
     phonemobile    CHAR(20),
     emailaddress   CHAR(100),
   PRIMARY KEY(customerNumber)
) CCSID EBCDIC;

CREATE UNIQUE INDEX iCustomer ON customer (customerNumber) CLUSTER;

CREATE TABLE customer_secure (
     customerNumber  INTEGER NOT NULL,
     customerPass    CHAR(32),
     state_indicator CHAR(1),
     pass_changes    INTEGER,
   PRIMARY KEY(customerNumber),
   FOREIGN KEY(customerNumber)
          REFERENCES customer (customerNumber)
          ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iCustomer_secure ON customer_secure (customerNumber) CLUSTER;

CREATE TABLE policy (
     policyNumber     INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                       (START WITH 1000001, INCREMENT BY 1, CACHE 20),
     customerNumber   INTEGER NOT NULL,
     issueDate        DATE,
     expiryDate       DATE,
     policyType       CHAR(1),
     lastChanged      TIMESTAMP NOT NULL WITH DEFAULT,
     brokerId         INTEGER,
     brokersReference CHAR(10),
     payment          INTEGER,
     commission       SMALLINT,
   PRIMARY KEY(policyNumber),
   FOREIGN KEY(customerNumber)
          REFERENCES customer (customerNumber)
          ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iPolicy  ON policy (policyNumber) CLUSTER;
CREATE INDEX        iPolicy2 ON policy (customerNumber);

CREATE TABLE endowment (
     policyNumber   INTEGER NOT NULL,
     equities       CHAR(1),
     withProfits    CHAR(1),
     managedFund    CHAR(1),
     fundName       CHAR(10),
     term           SMALLINT,
     sumAssured     INTEGER,
     lifeAssured    CHAR(31),
     paddingData    VARCHAR(32606),
   PRIMARY KEY(policyNumber),
   FOREIGN KEY(policyNumber)
          REFERENCES policy (policyNumber)
          ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iEndowment ON endowment (policyNumber) CLUSTER;

CREATE TABLE house (
     policyNumber   INTEGER NOT NULL,
     propertyType   CHAR(15),
     bedrooms       SMALLINT,
     value          INTEGER,
     houseName      CHAR(20),
     houseNumber    CHAR(4),
     postcode       CHAR(8),
   PRIMARY KEY(policyNumber),
   FOREIGN KEY(policyNumber)
          REFERENCES policy (policyNumber) ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iHouse ON house (policyNumber) CLUSTER;

CREATE TABLE motor (
     policyNumber      INTEGER NOT NULL,
     make              CHAR(15),
     model             CHAR(15),
     value             INTEGER,
     regNumber         CHAR(7),
     colour            CHAR(8),
     cc                SMALLINT,
     yearOfManufacture DATE,
     premium           INTEGER,
     accidents         INTEGER,
   PRIMARY KEY(policyNumber),
   FOREIGN KEY(policyNumber)
          REFERENCES policy (policyNumber) ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iMotor ON motor (policyNumber) CLUSTER;

CREATE TABLE Commercial (
  PolicyNumber       INTEGER      NOT NULL,
  RequestDate        TIMESTAMP,
  StartDate          DATE,
  RenewalDate        DATE,
  Address            CHAR(255),
  Zipcode            CHAR(8),
  LatitudeN          CHAR(11),
  LongitudeW         CHAR(11),
  Customer           CHAR(255),
  PropertyType       CHAR(255),
  FirePeril          SMALLINT,
  FirePremium        INTEGER,
  CrimePeril         SMALLINT,
  CrimePremium       INTEGER,
  FloodPeril         SMALLINT,
  FloodPremium       INTEGER,
  WeatherPeril       SMALLINT,
  WeatherPremium     INTEGER,
  Status             SMALLINT,
  RejectionReason    CHAR(255),
  PRIMARY KEY(policyNumber),
  FOREIGN KEY(policyNumber)
         REFERENCES policy (policyNumber) ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iCommercial ON Commercial (PolicyNumber) CLUSTER;

CREATE TABLE Claim (
  ClaimNumber        INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                       (START WITH 1000001, INCREMENT BY 1, CACHE 20),
  PolicyNumber       INTEGER      NOT NULL,
  ClaimDate          DATE,
  Paid               INTEGER,
  Value              INTEGER,
  Cause              CHAR(255),
  Observations       CHAR(255),
  PRIMARY KEY  (ClaimNumber),
  FOREIGN KEY  (PolicyNumber)
          REFERENCES Policy (PolicyNumber)
          ON DELETE CASCADE
) CCSID EBCDIC;

CREATE UNIQUE INDEX iClaim ON claim (ClaimNumber) CLUSTER;
