-- ================================================================
-- 02_target_schema.sql
-- PostgreSQL translation of ddl/db2_source_schema.sql, per the type
-- mapping rules in docs/MIGRATION_BLUEPRINT.md Section 1 and the
-- structural rules in Section 3:
--   - DB2 CHAR(n) fixed-length -> PostgreSQL VARCHAR(n). PostgreSQL's
--     CHAR(n) exists but is discouraged (it space-pads on read and
--     offers no performance benefit over VARCHAR internally); VARCHAR
--     preserves DB2's fixed-width *validation* without the padding
--     surprise. If byte-for-byte legacy padding behavior is required
--     by a downstream consumer, use CHAR(n) instead - see blueprint.
--   - DB2 INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH n)
--     -> PostgreSQL GENERATED BY DEFAULT AS IDENTITY (START WITH n)
--     (directly portable; PostgreSQL 10+ syntax matches DB2's here)
--   - DB2 SMALLINT -> PostgreSQL SMALLINT (identical range)
--   - DB2 TIMESTAMP NOT NULL WITH DEFAULT -> PostgreSQL
--     TIMESTAMP NOT NULL DEFAULT now()
--   - DB2 VARCHAR(32606) padding field -> keep as TEXT (no practical
--     reason to cap it in Postgres; see Section 3)
-- ================================================================
SET search_path TO genapp, public;

CREATE TABLE IF NOT EXISTS genapp.customer (
    customer_number  INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000001 INCREMENT BY 1),
    first_name       VARCHAR(10),
    last_name        VARCHAR(20),
    date_of_birth    DATE,
    house_name       VARCHAR(20),
    house_number     VARCHAR(4),
    postcode         VARCHAR(8),
    phone_home       VARCHAR(20),
    phone_mobile     VARCHAR(20),
    email_address    VARCHAR(100),
    PRIMARY KEY (customer_number)
);

CREATE TABLE IF NOT EXISTS genapp.customer_secure (
    customer_number   INTEGER NOT NULL,
    customer_pass     VARCHAR(32),
    state_indicator   VARCHAR(1),
    pass_changes      INTEGER,
    PRIMARY KEY (customer_number),
    FOREIGN KEY (customer_number) REFERENCES genapp.customer (customer_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS genapp.policy (
    policy_number      INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000001 INCREMENT BY 1),
    customer_number    INTEGER NOT NULL,
    issue_date         DATE,
    expiry_date        DATE,
    policy_type        VARCHAR(1),
    last_changed       TIMESTAMP NOT NULL DEFAULT now(),
    broker_id          INTEGER,
    brokers_reference  VARCHAR(10),
    payment            INTEGER,
    commission         SMALLINT,
    PRIMARY KEY (policy_number),
    FOREIGN KEY (customer_number) REFERENCES genapp.customer (customer_number) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_policy_customer_number ON genapp.policy (customer_number);

CREATE TABLE IF NOT EXISTS genapp.endowment (
    policy_number   INTEGER NOT NULL,
    equities        VARCHAR(1),
    with_profits    VARCHAR(1),
    managed_fund    VARCHAR(1),
    fund_name       VARCHAR(10),
    term            SMALLINT,
    sum_assured     INTEGER,
    life_assured    VARCHAR(31),
    padding_data    TEXT,
    PRIMARY KEY (policy_number),
    FOREIGN KEY (policy_number) REFERENCES genapp.policy (policy_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS genapp.house (
    policy_number   INTEGER NOT NULL,
    property_type   VARCHAR(15),
    bedrooms        SMALLINT,
    value           INTEGER,
    house_name      VARCHAR(20),
    house_number    VARCHAR(4),
    postcode        VARCHAR(8),
    PRIMARY KEY (policy_number),
    FOREIGN KEY (policy_number) REFERENCES genapp.policy (policy_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS genapp.motor (
    policy_number        INTEGER NOT NULL,
    make                 VARCHAR(15),
    model                VARCHAR(15),
    value                INTEGER,
    reg_number           VARCHAR(7),
    colour               VARCHAR(8),
    cc                   SMALLINT,
    year_of_manufacture  DATE,
    premium              INTEGER,
    accidents            INTEGER,
    PRIMARY KEY (policy_number),
    FOREIGN KEY (policy_number) REFERENCES genapp.policy (policy_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS genapp.commercial (
    policy_number     INTEGER NOT NULL,
    request_date      TIMESTAMP,
    start_date        DATE,
    renewal_date      DATE,
    address           VARCHAR(255),
    zipcode           VARCHAR(8),
    latitude_n        VARCHAR(11),
    longitude_w       VARCHAR(11),
    customer          VARCHAR(255),
    property_type     VARCHAR(255),
    fire_peril        SMALLINT,
    fire_premium      INTEGER,
    crime_peril       SMALLINT,
    crime_premium     INTEGER,
    flood_peril       SMALLINT,
    flood_premium     INTEGER,
    weather_peril     SMALLINT,
    weather_premium   INTEGER,
    status            SMALLINT,
    rejection_reason  VARCHAR(255),
    PRIMARY KEY (policy_number),
    FOREIGN KEY (policy_number) REFERENCES genapp.policy (policy_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS genapp.claim (
    claim_number    INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000001 INCREMENT BY 1),
    policy_number   INTEGER NOT NULL,
    claim_date      DATE,
    paid            INTEGER,
    value           INTEGER,
    cause           VARCHAR(255),
    observations    VARCHAR(255),
    PRIMARY KEY (claim_number),
    FOREIGN KEY (policy_number) REFERENCES genapp.policy (policy_number) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_claim_policy_number ON genapp.claim (policy_number);
