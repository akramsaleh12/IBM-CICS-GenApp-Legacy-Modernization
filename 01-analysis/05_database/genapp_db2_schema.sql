-- ---------------------------------------------------------------------
-- CUSTOMER  (party master)
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.customer (
     customerNumber INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                     (START WITH 1000001, INCREMENT BY 1, CACHE 20),
     firstName      CHAR(10),
     lastName       CHAR(20),
     dateOfBirth    DATE,
     houseName      CHAR(20),
     houseNumber    CHAR(4),
     postcode       CHAR(8),
     phonehome      CHAR(20),
     phonemobile    CHAR(20),
     emailaddress   CHAR(100),
   PRIMARY KEY (customerNumber))
   CCSID EBCDIC
   IN <DB2DBID>.GENATS00;

CREATE UNIQUE INDEX <DB2DBID>.iCustomer
   ON <DB2DBID>.customer (customerNumber) CLUSTER COPY YES;

-- ---------------------------------------------------------------------
-- CUSTOMER_SECURE  (1:1 security/password row per customer)
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.customer_secure (
     customerNumber  INTEGER NOT NULL,
     customerPass    CHAR(32),
     state_indicator CHAR(1),
     pass_changes    INTEGER,
   PRIMARY KEY (customerNumber),
   FOREIGN KEY (customerNumber)
          REFERENCES <DB2DBID>.customer (customerNumber)
          ON DELETE CASCADE)
   CCSID EBCDIC
   IN <DB2DBID>.GENATS01;

CREATE UNIQUE INDEX <DB2DBID>.iCustomer_secure
   ON <DB2DBID>.customer_secure (customerNumber) CLUSTER COPY YES;

-- ---------------------------------------------------------------------
-- POLICY  (transaction/policy master; policyType = M/E/H/C discriminator)
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.policy (
     policyNumber     INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                       (START WITH 1000001, INCREMENT BY 1, CACHE 20),
     customerNumber   INTEGER NOT NULL,
     issueDate        DATE,
     expiryDate       DATE,
     policyType       CHAR(1),
     lastChanged      TIMESTAMP NOT NULL WITH DEFAULT,
     brokerId         INTEGER,
     brokersReference CHAR(10),
     payment          INTEGER,
     commission       SMALLINT,
   PRIMARY KEY (policyNumber),
   FOREIGN KEY (customerNumber)
          REFERENCES <DB2DBID>.customer (customerNumber)
          ON DELETE CASCADE)
   CCSID EBCDIC
   IN <DB2DBID>.GENATS02;

CREATE UNIQUE INDEX <DB2DBID>.iPolicy
   ON <DB2DBID>.policy (policyNumber) CLUSTER COPY YES;
CREATE INDEX <DB2DBID>.iPolicy2
   ON <DB2DBID>.policy (customerNumber) COPY YES;

-- ---------------------------------------------------------------------
-- ENDOWMENT  (1:1 policy-type-detail child, policyType = 'E')
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.endowment (
     policyNumber   INTEGER NOT NULL,
     equities       CHAR(1),
     withProfits    CHAR(1),
     managedFund    CHAR(1),
     fundName       CHAR(10),
     term           SMALLINT,
     sumAssured     INTEGER,
     lifeAssured    CHAR(31),
     paddingData    VARCHAR(32606),
   PRIMARY KEY (policyNumber),
   FOREIGN KEY (policyNumber)
          REFERENCES <DB2DBID>.policy (policyNumber)
          ON DELETE CASCADE)
   CCSID EBCDIC
   IN <DB2DBID>.GENATS03;

CREATE UNIQUE INDEX <DB2DBID>.iEndowment
   ON <DB2DBID>.endowment (policyNumber) CLUSTER COPY YES;

-- ---------------------------------------------------------------------
-- HOUSE  (1:1 policy-type-detail child, policyType = 'H')
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.house (
     policyNumber   INTEGER NOT NULL,
     propertyType   CHAR(15),
     bedrooms       SMALLINT,
     value          INTEGER,
     houseName      CHAR(20),
     houseNumber    CHAR(4),
     postcode       CHAR(8),
   PRIMARY KEY (policyNumber),
   FOREIGN KEY (policyNumber)
          REFERENCES <DB2DBID>.policy (policyNumber) ON DELETE CASCADE)
   CCSID EBCDIC
   IN <DB2DBID>.GENATS04;

CREATE UNIQUE INDEX <DB2DBID>.iHouse
   ON <DB2DBID>.house (policyNumber) CLUSTER COPY YES;

-- ---------------------------------------------------------------------
-- MOTOR  (1:1 policy-type-detail child, policyType = 'M')
