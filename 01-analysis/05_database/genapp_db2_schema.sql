-- ---------------------------------------------------------------------
-- CLAIM  (child of policy; no maintaining COBOL program in this package)
-- ---------------------------------------------------------------------
CREATE TABLE <DB2DBID>.Claim (
  ClaimNumber   INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
                (START WITH 1000001, INCREMENT BY 1, CACHE 20),
  PolicyNumber  INTEGER NOT NULL,
  ClaimDate     DATE,
  Paid          INTEGER,
  Value         INTEGER,
  Cause         CHAR(255),
  Observations  CHAR(255),
  PRIMARY KEY (ClaimNumber),
  FOREIGN KEY (PolicyNumber)
          REFERENCES <DB2DBID>.Policy (PolicyNumber)
          ON DELETE CASCADE)
 CCSID EBCDIC
 IN <DB2DBID>.GENATS07;

